MAX_VALUE = 32.5   # uv5*3 + sv5*2 + dr2*1.5 + cw3*1.5


def score(r: dict, st: dict) -> tuple[float, str]:
    """Value-led, cost-dampened, stage-gated.

    Cost DAMPENS rather than divides: an earlier version divided by cost and
    produced scores of 47 for trivial work while a one-way architecture
    decision sank to P3. Expensive strategic work must not be crushed by a
    bang-for-buck metric.
    """
    if r["destination"] == "ignore":
        return 0.0, "P4"

    cost = COST.get(r["cost"], 2)
    maint = MAINT.get(r["maint"], 2)
    cw = CONF_W.get(r["conf"], 1)
    dr = 2 if r.get("debt_reduced") else 0

    value = (r["uv"] * 3 + r["sv"] * 2 + dr * 1.5 + cw * 1.5) / MAX_VALUE * 10
    effort = 1 / (1 + 0.25 * cost + 0.1 * maint)
    s = value * effort

    # Irreversibility urgency: a one-way decision left open gets more
    # expensive every week. Timing matters more than cost here.
    if r["destination"] == "adr" and r.get("adr_ref"):
        s *= 1.8

    exit_ids = {c["id"] for c in st["open_blocking"]}
    if r["stage"] <= st["current"]:
        s *= 1.5 if (set(r.get("deps", [])) & exit_ids
                     or r.get("milestone_ref") in exit_ids) else 1.0
    elif r["stage"] <= st["current"] + 1:
        s *= 0.4
    else:
        s *= 0.1

    s = min(s, 10.0)
    for lo, band in ((6.0, "P0"), (4.0, "P1"), (2.5, "P2"), (1.0, "P3")):
        if s >= lo:
            return round(s, 2), band
    return round(s, 2), "P4"


def gate(r: dict, st: dict) -> tuple[bool, str]:
    """Stage discipline. No override exists, by design."""
    if r["stage"] <= st["current"]:
        return True, ""
    if st["open_blocking"]:
        names = ", ".join(c["id"] for c in st["open_blocking"][:3])
        return False, (f"stage {r['stage']} > current {st['current']:g} and "
                       f"{len(st['open_blocking'])} blocking prerequisites open "
                       f"({names}...)")
    return True, ""


def route_all() -> None:
    st = stage_state()
    print(f"\n{C['b']}DESIGN INTELLIGENCE ROUTER{C['x']}")
    print(f"  current stage {C['c']}{st['current']:g}{C['x']} · "
          f"{len(st['open_blocking'])} blocking exit criteria open\n")

    rows = []
    for r in ROUTES:
        s, band = score(r, st)
        allowed, reason = gate(r, st)
        dest = r["destination"] if allowed else "parked"
        rows.append((s, band, dest, r, reason))
    rows.sort(key=lambda x: -x[0])

    dcol = {"adr": C["m"], "rfc": C["c"], "research": C["y"],
            "issue": C["g"], "milestone": C["b"], "parked": C["d"],
            "ignore": C["d"]}
    bcol = {"P0": C["r"], "P1": C["y"], "P2": C["c"], "P3": C["d"], "P4": C["d"]}

    print(f"  {'pri':<4} {'score':>5}  {'destination':<11} {'stg':<4} title")
    print(f"  {'-'*4} {'-'*5}  {'-'*11} {'-'*4} {'-'*52}")
    for s, band, dest, r, reason in rows:
        print(f"  {bcol[band]}{band:<4}{C['x']} {s:>5.2f}  "
              f"{dcol.get(dest,'')}{dest:<11}{C['x']} "
              f"{r['stage']:<4g} {r['title'][:52]}")
        if reason:
            print(f"       {C['d']}gated: {reason}{C['x']}")

    counts: dict[str, int] = {}
    for _, _, d, _, _ in rows:
        counts[d] = counts.get(d, 0) + 1
    print(f"\n  {C['b']}routing{C['x']}  " +
          "  ".join(f"{k}:{v}" for k, v in sorted(counts.items())))
    parked = [r for _, _, d, r, _ in rows if d == "parked"]
    if parked:
        print(f"  {C['d']}{len(parked)} parked — preserved with unpark triggers, "
              f"not discarded{C['x']}")
    print()


def stage_check() -> None:
    st = stage_state()
    print(f"\n{C['b']}STAGE DISCIPLINE CHECK{C['x']}\n")
    print(f"  current stage: {C['c']}{st['current']:g}{C['x']}")
    print(f"  exit criteria: {len(st['criteria'])} total, "
          f"{C['r']}{len(st['open_blocking'])} blocking still open{C['x']}\n")
    for c in st["criteria"]:
        if c["status"] == "complete":
            print(f"    {C['g']}done{C['x']}    {c['id']:<8} {c['name'][:58]}")
        else:
            mark = f"{C['r']}BLOCK{C['x']}" if c["blocking"] else f"{C['y']}open {C['x']}"
            print(f"    {mark}   {c['id']:<8} {c['name'][:58]}")

    violations = []
    for r in ROUTES:
        allowed, _ = gate(r, st)
        if not allowed and r["destination"] not in ("parked", "ignore"):
            violations.append(r)
    print(f"\n  {C['b']}discipline enforcement{C['x']}")
    if violations:
        print(f"    {C['y']}{len(violations)} recommendation(s) auto-parked "
              f"by the stage gate:{C['x']}")
        for r in violations:
            print(f"      {r['id']} stage {r['stage']:g} → parked "
                  f"({r['destination']} withheld)")
    else:
        print(f"    {C['g']}no violations — all recommendations stage-admissible{C['x']}")
    print(f"\n  {C['d']}No override flag exists. An override would be used, and the"
          f"\n  discipline would erode exactly under delivery pressure.{C['x']}\n")


def explain(rid: str) -> None:
    st = stage_state()
    r = next((x for x in ROUTES if x["id"] == rid), None)
    if not r:
        print(f"unknown: {rid}")
        return
    s, band = score(r, st)
    allowed, reason = gate(r, st)
    dest = r["destination"] if allowed else "parked"

    print(f"\n{C['b']}{r['id']} — {r['title']}{C['x']}\n")
    print(f"  {C['d']}source insight:{C['x']} {r['source']} ({r['src_reg']})\n")
    qs = [
        ("1  Does this affect JARVIS?", "yes" if r["affects"] else "no"),
        ("2  Affected stage", f"{r['stage']:g}"),
        ("3  Affected subsystem", r["subsystem"] or "—"),
        ("4  Introduces new module?", "yes" if r["new_module"] else "no"),
        ("5  Invalidates a decision?", r["invalidates"] or "no"),
        ("6  Strengthens / weakens?", r["design_effect"]),
        ("7  Creates technical debt?", "yes" if r["debt_created"] else "no"),
        ("8  Reduces technical debt?", "yes" if r["debt_reduced"] else "no"),
        ("9  ADR?", "YES" if r["destination"] == "adr" else "no"),
        ("10 RFC?", "YES" if r["destination"] == "rfc" else "no"),
        ("11 Research project?", "YES" if r["destination"] == "research" else "no"),
        ("12 GitHub Issue?", "YES" if r["destination"] == "issue" else "no"),
        ("13 Milestone?", "YES" if r["destination"] == "milestone" else "no"),
        ("14 Future-stage idea?", "YES" if dest == "parked" else "no"),
        ("15 Ignore?", "YES" if r["destination"] == "ignore" else "no"),
    ]
    for q, a in qs:
        print(f"    {q:<30} {C['c']}{a}{C['x']}")

    print(f"\n  {C['b']}mandatory fields{C['x']}")
    for k, v in [
        ("implementation cost", r["cost"]), ("maintenance burden", r["maint"]),
        ("dependency graph", ", ".join(r["deps"]) or "none"),
        ("expected user value", f"{r['uv']}/5"),
        ("strategic value", f"{r['sv']}/5"),
        ("evidence confidence", r["conf"]),
        ("recommended priority", f"{band} (score {s})"),
        ("review trigger", r["review"]),
    ]:
        print(f"    {k:<24} {v}")

    if reason:
        print(f"\n  {C['y']}STAGE GATE: parked{C['x']}\n    {reason}")
        if r.get("unpark"):
            print(f"    unpark trigger: {r['unpark']}")
    print(f"\n  {C['b']}reasoning{C['x']}\n    {r['why']}\n")


def roadmap() -> None:
    st = stage_state()
    rows = []
    for r in ROUTES:
        s, band = score(r, st)
        allowed, _ = gate(r, st)
        rows.append((s, band, r["destination"] if allowed else "parked", r))
    rows.sort(key=lambda x: -x[0])

    lines = [
        "# JARVIS Engineering Roadmap",
        "",
        "**Generated** by `tools/route.py` from the registry substrate.",
        "Not hand-written. Regenerates on every `evolve.py` run.",
        "",
        f"Current stage **{st['current']:g}** · "
        f"{len(st['open_blocking'])} blocking exit criteria open",
        "",
        "> Stage discipline is enforced mechanically: no stage-N recommendation",
        "> is emitted while stage-(N-1) blocking prerequisites remain open.",
        "> Parked items are preserved with unpark triggers, never discarded.",
        "",
        "| Pri | Score | Route | Stage | Subsystem | Recommendation | Cost | Conf |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s, band, dest, r in rows:
        lines.append(
            f"| **{band}** | {s:.2f} | {dest} | {r['stage']:g} | "
            f"`{r['subsystem'] or '—'}` | {r['title']} | {r['cost']} | {r['conf']} |"
        )

    lines += ["", "## P0 — blocks stage exit", ""]
    for s, band, dest, r in rows:
        if band == "P0":
            lines += [
                f"### {r['id']} · {r['title']}",
                f"- **Stage** {r['stage']:g} · **Subsystem** `{r['subsystem']}`"
                f" · **Route** {dest}",
                f"- **Cost** {r['cost']} · **Maintenance** {r['maint']}"
                f" · **Confidence** {r['conf']}",
                f"- **User value** {r['uv']}/5 · **Strategic value** {r['sv']}/5",
                f"- **Dependencies** {', '.join(r['deps']) or 'none'}",
                f"- **Review trigger** {r['review']}",
                f"- **Source** `{r['source']}`",
                "", f"{r['why']}", "",
            ]

    parked = [(s, r) for s, b, d, r in rows if d == "parked"]
    if parked:
        lines += ["## Parked — future-stage, preserved", ""]
        for s, r in parked:
            lines.append(f"- **{r['id']}** {r['title']} — stage {r['stage']:g}, "
                         f"unpark: _{r.get('unpark', 'stage prerequisites complete')}_")
        lines.append("")

    (OUT / "ROADMAP.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\n  {C['g']}wrote{C['x']} design-intelligence/ROADMAP.md  "
          f"({len(rows)} recommendations)\n")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    a = sys.argv[1]
    if a == "--all":
        route_all()
    elif a == "--stage-check":
        stage_check()
    elif a == "--roadmap":
        roadmap()
    elif a == "--explain" and len(sys.argv) > 2:
        explain(sys.argv[2])
    else:
        print(__doc__)
        sys.exit(2)
