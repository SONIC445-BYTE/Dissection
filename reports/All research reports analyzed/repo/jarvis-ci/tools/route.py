# ── stage model ──────────────────────────────────────────────────────────
def stage_state() -> dict:
    text = (MODEL / "stage-model.yaml").read_text(encoding="utf-8")
    cur = float(re.search(r"current_stage:\s*([\d.]+)", text).group(1))
    crits = []
    for m in re.finditer(
        r"-\s+id:\s*(S[\w.-]+)\n\s+name:\s*\"?(.*?)\"?\n\s+status:\s*(\w+)"
        r"(?:\n\s+blocking:\s*(\w+))?", text
    ):
        crits.append({"id": m.group(1), "name": m.group(2),
                      "status": m.group(3), "blocking": m.group(4) == "true"})
    open_blocking = [c for c in crits
                     if c["status"] == "open" and c["blocking"]]
    return {"current": cur, "criteria": crits, "open_blocking": open_blocking}


def subsystems() -> dict:
    return {s["id"]: s for s in load_items("subsystem-map.yaml", "subsystems")
            } if (MODEL / "subsystem-map.yaml").exists() else {}


def _load_model_items(fname: str, key: str) -> list[dict]:
    """load_items reads from registries/; subsystem map lives in jarvis-model/."""
    import ask
    orig = ask.REG
    ask.REG = MODEL
    try:
        return ask.load_items(fname, key)
    finally:
        ask.REG = orig


